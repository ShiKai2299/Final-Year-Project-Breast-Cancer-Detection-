import matplotlib.pyplot as plt
import seaborn as sns
import numpy as np

"""**ENTER EACH EXPERIMENT**

Insert value and calculate the average of the f1-score for benign and malignant.
"""

experiments = [
    "Cropped DDSM",
    "Original DDSM",
    "Combination Dataset V1",
    "Combination Dataset V2"
]

accuracy = [0.61, 0.63, 0.67, 0.64]
benign_f1 = [0.59, 0.51, 0.68, 0.65]
malignant_f1 = [0.62, 0.70, 0.65, 0.63]
malignant_recall = [0.63, 0.87, 0.70, 0.69]

# Calculate Macro F1
macro_f1 = [(b + m) / 2 for b, m in zip(benign_f1, malignant_f1)]

"""# GRAPH of COMPARISON EXPERIMENTAL CONFIGUREATIONS

Value (Accuracy, Macro F1 and Malignant Recall) for each experiments.
"""

x = np.arange(len(experiments))
width = 0.25

plt.figure(figsize=(12, 6))
plt.bar(x - width, accuracy, width, label='Accuracy')
plt.bar(x, macro_f1, width, label='Macro F1')
plt.bar(x + width, malignant_recall, width, label='Malignant Recall')

plt.xticks(x, experiments, rotation=15)
plt.ylim(0, 1.0)
plt.ylabel("Score")
plt.title("Comparison of Experimental Configurations")
plt.legend()
plt.tight_layout()
plt.show()

"""# GRAPH ACCURACY COMPARISON OF DIFFERENT EXPERIMENTS"""

plt.figure(figsize=(8, 5))
bars = plt.bar(experiments, accuracy)
plt.ylim(0, 1.0)
plt.ylabel("Accuracy")
plt.title("Accuracy")

for bar, val in zip(bars, accuracy):
    plt.text(bar.get_x() + bar.get_width()/2, val + 0.01, f"{val:.2f}",
             ha='center', va='bottom')

plt.tight_layout()
plt.show()

"""# GRAPH MACRO F1-SCORE

"""

plt.figure(figsize=(8, 5))
bars = plt.bar(experiments, macro_f1)
plt.ylim(0, 1.0)
plt.ylabel("Macro F1-score")
plt.title("Macro F1-score")

for bar, val in zip(bars, macro_f1):
    plt.text(bar.get_x() + bar.get_width()/2, val + 0.01, f"{val:.2f}",
             ha='center', va='bottom')

plt.tight_layout()
plt.show()

"""# GRAPH MALIGNANT RECALL"""

plt.figure(figsize=(8, 5))
bars = plt.bar(experiments, malignant_recall)
plt.ylim(0, 1.0)
plt.ylabel("Malignant Recall")
plt.title("Malignant Recall")

for bar, val in zip(bars, malignant_recall):
    plt.text(bar.get_x() + bar.get_width()/2, val + 0.01, f"{val:.2f}",
             ha='center', va='bottom')

plt.tight_layout()
plt.show()

"""# CONFUSION MATRIX (HEATMAPS)"""

cm = np.array([[155, 89],
               [57, 135]])

labels = ["Benign", "Malignant"]

plt.figure(figsize=(6,5))
sns.heatmap(cm, annot=True, fmt="d", cmap="Blues",
            xticklabels=labels, yticklabels=labels)

plt.title("Confusion Matrix (Combination Dataset Version 1)")
plt.xlabel("Predicted Label")
plt.ylabel("True Label")
plt.tight_layout()
plt.show()

"""# GRAPH MODEL PERFORMANCE (PRECISION & RECALL)"""

labels = ['Benign Precision', 'Malignant Precision', 'Benign Recall', 'Malignant Recall']
values = [0.73, 0.60, 0.64, 0.70]

plt.figure(figsize=(8,5))
plt.bar(labels, values)

plt.ylim(0, 1)
plt.ylabel("Score")
plt.title("Model Performance")

for i, v in enumerate(values):
    plt.text(i, v + 0.02, f"{v:.2f}", ha='center')

