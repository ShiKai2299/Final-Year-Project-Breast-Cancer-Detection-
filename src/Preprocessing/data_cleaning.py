"""**CREATE FOLDER**

Develop sub-folder inside the target file.

*   normal
*   benign
*   malignant



"""

os.makedirs(target_normal, exist_ok=True)
os.makedirs(target_benign, exist_ok=True)
os.makedirs(target_malignant, exist_ok=True)

"""**COPY IMAGE**

Copy image into the target file.
"""

# Copy NORMAL
for img in os.listdir(source_normal):
    shutil.copy(
        os.path.join(source_normal, img),
        target_normal
    )

# Copy BENIGN
for img in os.listdir(source_benign):
    shutil.copy(
        os.path.join(source_benign, img),
        target_benign
    )

# Copy MALIGNANT (BI-RADS 4 + 5)
for malignant_folder in source_malignant:
    for img in os.listdir(malignant_folder):
        shutil.copy(
            os.path.join(malignant_folder, img),
            target_malignant
        )